"""
2. В матрице найти среднее арифметическое положительных элементов, кратных 3.
"""

m = [
    [25, 28, -31, -29],
    [18, -20, 22, 19],
    [38, 30, -30, 30],
    [27, -35, 26, -24]
]

r = []

for i in range(len(m)):
    for j in range(len(m[i])):
        if m[i][j] > 0 and m[i][j] % 3 == 0:
            r.append((m[i][j]))

s = sum(r) / len(r)
print(s)
